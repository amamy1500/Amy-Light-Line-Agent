// Bundles supabase/migrations/*.sql into lib/db/migrations.generated.ts so the app can
// migrate an embedded database without reading files at runtime.
// Run after editing any migration: npm run db:bundle
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "supabase", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

const entries = files.map((file) => {
  const sql = readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n");
  return `  { id: ${JSON.stringify(file.replace(/\.sql$/, ""))}, sql: ${JSON.stringify(sql)} },`;
});

const out = `// GENERATED by scripts/bundle-migrations.mjs from supabase/migrations/*.sql. Do not edit.
import type { Migration } from "./migrate";

export const migrations: readonly Migration[] = [
${entries.join("\n")}
];
`;

writeFileSync(join(root, "lib", "db", "migrations.generated.ts"), out);
console.log(`bundled ${files.length} migration(s): ${files.join(", ")}`);
